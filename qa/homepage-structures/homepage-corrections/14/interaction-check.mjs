import {chromium} from '/opt/codex/cua_node/lib/node_modules/playwright/index.mjs';
import fs from 'node:fs/promises';
const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'no-preference'});
const remote=[];page.on('request',r=>{if(!r.url().startsWith('http://127.0.0.1:4207/'))remote.push(r.url());});
await page.goto('http://127.0.0.1:4207/qa/homepage-structures/homepage-corrections/14/index.html');
await page.waitForFunction(()=>document.documentElement.dataset.homepageReady==='14');
const link=page.locator('#current-pair [data-cross]');await link.click();
const motion=await page.evaluate(()=>({target:document.activeElement.id,animations:document.getAnimations().map(a=>({duration:a.effect.getTiming().duration,state:a.playState}))}));
if(motion.target!=='ai-0'||!motion.animations.some(a=>a.duration===180))throw new Error('Pointer arrival missing '+JSON.stringify(motion));
await page.evaluate(()=>{const query=matchMedia('(prefers-reduced-motion:reduce)');window.only14MotionCheck={started:performance.now()};query.addEventListener('change',()=>{window.only14MotionCheck={...window.only14MotionCheck,eventAt:performance.now(),active:document.getAnimations().length,matches:query.matches};},{once:true});});
await page.emulateMedia({reducedMotion:'reduce'});
await page.waitForFunction(()=>window.only14MotionCheck.matches===true);
const preferenceEvent=await page.evaluate(()=>window.only14MotionCheck);
const cancelled=preferenceEvent.active===0;
if(!cancelled)throw new Error('Live reduced motion did not cancel');
await page.locator('[data-return]').click();
await page.locator('#edition-switch').click();await page.waitForFunction(()=>document.documentElement.dataset.homepageReady==='14');
const publicEdition=await page.evaluate(()=>({search:location.search,private:!!document.querySelector('#team-value'),archives:document.querySelectorAll('.archive-story').length}));
if(publicEdition.private||!publicEdition.search.includes('public'))throw new Error('Edition switch failed');
await page.goBack();await page.waitForFunction(()=>document.documentElement.dataset.homepageReady==='14');
const back=await page.evaluate(()=>!!document.querySelector('#team-value'));
if(!back||remote.length)throw new Error(JSON.stringify({back,remote}));
const output={checkedAt:new Date().toISOString(),motion,cancelled,preferenceEvent,publicEdition,back,remote};
await fs.writeFile(new URL('./interaction-checks.json',import.meta.url),JSON.stringify(output,null,2));
console.log(JSON.stringify(output));await browser.close();
